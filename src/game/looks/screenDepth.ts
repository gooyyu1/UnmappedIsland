/**
 * 画面に重ねる層の階梯。奥から手前へ、この宣言の順に並ぶ。
 *
 * 前後関係は2段で決まる。**まず層（depth）、同じ層の中は生成順**——後に作ったものが手前に来る。
 * 層を指定しない表示物は既定の層（0）に居るので、この宣言に0は現れない。
 *
 * **層の値は1箇所にだけ書く**——値を別々の場所に置くと、隣り合う2つの前後関係しか分からず、
 * 離れた2つが入れ替わったことに気付けない。層をまたいで手前へ出したくなったら、その場で
 * 持ち上げるのではなくここへ層を足す（Tooltipがその形）。シーンの表示リストは層が動いたときにしか
 * 並べ直さないので、**持ち上げたものは次の並べ直しまで、どの層よりも手前に居てしまう。**
 *
 * **同じ層の中の前後関係は、ここには載らない。** 生成順そのものなので、何を先に作るかは組み立てる
 * その場（部品の構築子）が決める。
 */
export const SCREEN_DEPTH = {
  /**
   * フィールドエリアの表示物。既定の層より奥へ置くことで、フィールドエリアだけを作り直しても
   * （PlayScene.rebuildFieldArea）背景板より奥に居ることを保証する——描画順に頼ると、作り直した
   * ぶんが背景板より手前へ入ってしまう。
   */
  field: -1,
  /** 雨の演出。カードの上に降らせつつ、はみ出したカードを隠す背景板の上には出さない。 */
  weather: -0.5,
  /**
   * 枠の外を飛んでいるカード（CardTable）。レーンの中に置いたままでは、はみ出したカードを隠す
   * 背景板をまたげない。
   */
  flyingCard: 1,
  /** 砂埃。埃は場に舞うものなので、飛んでいる札より手前・時間帯の明るさはカードと同じだけ受ける。 */
  dust: 1.2,
  /**
   * 長押し・ドラッグ中に出す吹き出し（Tooltip）。**基準にした札やボタンより必ず手前**——生成順に
   * 頼ると、後から作られた札やボタンの陰に入る。
   */
  tooltip: 1.3,
  /** 日射に応じた翳り・輝き。画面全体にかぶるので、飛んでいるカードより手前。 */
  skyTint: 1.5,
  /**
   * 日の出・日の入りの演出。**翳りより手前**——夜をまたぐ演出なので、翳りの下では出した意味が無い。
   * ドーナツグラフより奥に留めるのは、経過時間を隠さないため（回復の粒と同じ理由）。
   */
  daybreak: 1.6,
  /** 回復の粒。翳りより手前（同じ明るさで読める）・ドーナツグラフより奥（経過時間を隠さない）。 */
  gainParticle: 1.75,
  /** ドーナツグラフ。飛んでいるカードも探索の子ウィンドウも越えて出す。 */
  ring: 2,
  /**
   * 札の上に浮かぶ出来事の文字（floatSignalLabel）。一瞬しか出ないので、たまたま重なった物の
   * 陰に入ってはならない。
   */
  signal: 2.5,
  /** 致命的域を伝える画面全体の枠。暗い時間帯でも変わらず読めている必要がある。 */
  alertFrame: 3,
} as const;

/**
 * 層の値。層を受け取る口（CardLane）はこの型で受けるので、階梯に無い数は渡せない——素の`number`で
 * 受けると、そこが階梯の外で値を決める2箇所目になる。
 */
export type ScreenDepth = (typeof SCREEN_DEPTH)[keyof typeof SCREEN_DEPTH];
