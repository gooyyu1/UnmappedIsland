#!/usr/bin/env bash
# メタMCP（`mcp__ccr_meta__*`）のツールを、トークンを読み直しながら呼ぶ。
#
#   bash .claude/ccr-meta.sh list_sessions <<<'{"limit": 5}'
#   bash .claude/ccr-meta.sh archive_session <<<'{"session_id": "cse_..."}'
#   bash .claude/ccr-meta.sh create_session < args.json
#
# **引数は標準入力で渡す**（argvではない）。中身は tools/call の arguments そのもので、**普段の
# `mcp__ccr_meta__*` と同じ道具・同じ引数**なので覚え直すことは無い。使えるのは `tools/list` で
# 引ける全部。
#
# **バッククォートを含む引数は、ファイルへ書いてから流す。** 危ないのは文字の符号ではなく**シェルの
# 展開**で、ヒアドキュメントに直に書くと中身が実行される（下記）。文字化けは考えなくてよい——node は
# argv も環境変数も標準入力もUTF-8で受ける（2026-09-05 に、コードページ932のまま実測）。
#
# ## なぜこれが要るのか — 入口はこれ1つ
#
# **`mcp__ccr_meta__*` は使わない。** あれは**起動時のヘッダを掴んだまま**なので、走っている最中に
# トークンが切れると、登録を直しても**そのセッションからは二度と使えない**（2026-08-25 に2回起きた）。
# しかも登録には固定のアクセストークンが平文で載る。
#
# **ここは呼ぶたびに `~/.claude/.credentials.json` から読み直す**ので切れず、トークンも持たない。
#
# **登録そのもの（`~/.claude.json` の `mcpServers`）は、あえて残してある。** 消すと道具の一覧からも
# 消えて、今度は「そもそも手が無い」と読んで諦める。見えたまま残し、呼んだところを
# [`hooks/deny-ccr-meta-mcp.sh`](hooks/deny-ccr-meta-mcp.sh) が捕まえてここへ案内する。
#
# **だから、登録のトークンは生かしておく必要がある。** 起動時にヘッダが無効だと**道具は一覧に
# 出ず**（2026-09-05 に実測。無効な値を入れて立てたセッションは `mcp__ccr_meta__*` を1つも持たなかった）、
# フックも呼ばれないので案内ごと消える。タスクスケジューラの `ClaudeCode-CcrMetaTokenSync` が
# `~/.claude/refresh-ccr-meta-token.ps1` を回して追従させている（登録のヘッダは
# [`scripts/usage/mcp.sh`](../scripts/usage/mcp.sh) も読んで直に叩くので、そちらのためにも要る）。
#
# MCPサーバもただのHTTPで、しかも**ステートレスに応じる**（`initialize` で session id を持たされない）
# ので、`tools/call` を1発投げるだけでよい。
#
# **RESTを逆算しない。** `/v1/code/sessions` を直に叩く道もあるが、形が違ううえ、**`DELETE` は畳まずに
# 消す**。同じ意味の操作を2通り持つ理由が無いので、道具はMCP側に揃える。
#
# ## 指示は Write で書く。シェルの展開を通さない
#
# **ヒアドキュメントで組み立てない。** 区切りを引用しない `<<EOF` は中身の `` `...` `` を**コマンドとして
# 実行する**ので、バッククォートで囲んだ識別子が黙って消える（2026-08-25 に実測。「`ClimateSystem.md`
# のような」が「 のような」になったまま届いた）。**このリポジトリの指示は識別子をバッククォートで
# 囲む書き方なので、必ず踏む。**
#
# 区切りを引用すれば（`<<'EOF'`）展開は止まるが、今度は変数を埋められない。**指示の本文は Write で
# ファイルへ書き、JSONの組み立てだけを node にやらせる**のが、どちらも踏まない唯一の形。
#
# ## 立てたら、届いた本文を読んで確かめる
#
# **欠けても壊れても、セッションは普通に動き出す。** 指示の一部が抜けたまま、それらしくファイルを
# 読み始めるので、**動いている様子は「無事に届いた」の根拠にならない**（2026-08-25 に、丸ごと化けた
# 指示のまま20分走った）。届いた本文そのものを突き合わせる。
#
# ```bash
# printf '%s' '{"session_id":"<id>","limit":100}' > "$LOCALAPPDATA/Temp/ev.json"
# bash .claude/ccr-meta.sh list_events < "$LOCALAPPDATA/Temp/ev.json"
# ```
#
# 最も古い `user` のイベントが送った本文。**元のファイルと突き合わせて一致を見る**（目視で「読める」
# ではなく、文字列の比較で）。
#
# 応答は `<other-session>` の包みに入って返る（他のセッションの記録なので）。**`grep -o '{"ccr".*'` で
# 中のJSONだけ取り出す。** そのまま `JSON.parse` すると包みの `<` で落ちる。
#
# ## `send_message` で送った本文は、`<` `>` が実体参照になる
#
# 受け取る側では `&lt;` `&gt;` として見える（2026-08-26 に実測。試験名の `A > B` が `A &gt; B` で届いた）。
# 日本語もバッククォートもそのまま通るので**化けたようには見えない**が、`=>` や `->` を含むコードを
# 送ると読めない形になる。**コードを渡すならファイルのパスを指して読ませる。**
#
# 本文は各行が4スペース字下げされて包まれる。突き合わせるときは字下げと実体参照を戻してから比べる。
#
# イベントの `user` にはツールの結果も混ざるので、**`message.content` が文字列のものだけ**が送った本文。
#
# ## リポジトリの渡し方を間違えると、空の箱で走り出す
#
# `create_session` に渡すのは **`source_url` / `source_revision`（平の引数）**。RESTの
# `config.sources` の形で書くと**黙って無視され**、リポジトリの無い `/home/user` で起動する
# （2026-08-25 に1回やった）。**立てた直後に `get_session` で `session_context.sources` を見て、
# 入っていることを確かめる。**
#
# ## この経路から立てるときに要る引数・渡してはいけない引数
#
# `mcp__ccr_meta__create_session` は呼び元のセッションから環境と権限を継ぐが、**HTTPを直に叩くこの
# 経路には呼び元が無い**ので、継ぐはずのものが継げない（2026-08-25 に2回撥ねられた）。
#
# - **`environment_id` は必須。** 省くと候補を並べたエラーが返る。クラウドは「デフォルト」のほう
#   （もう一方はこのPCのブリッジ環境で、`source_url` を渡す使い方と噛み合わない）。
# - **`permission_mode` は `bypassPermissions` だけが撥ねられる**
#   （`requires a CCR parent session; this caller path has none`）。`auto` などは通る。
#   **どれを渡すかは投入先で決まる**ので、[`ccr-env.sh`](../scripts/agent/ccr-env.sh) から取る
#   ——**手で立てるときも同じ**。省くのは「手元の `settings.json` の `defaultMode` に従え」の意味で、
#   ブリッジでは `bypassPermissions` になるが、クラウドでは箱に設定が無いので `ask` で走り、
#   `.claude/**` に触れた時点で降りない承認を待つ。
# - **`prompt` を渡さないと、手番が一度も走らない。** 立ってはいるが承認モードは手動に見え、
#   タグも指示も無いセッションが残る。**立てるなら最初の1手を渡す。**

set -euo pipefail

TOOL="${1:?ツール名を渡す（例: list_sessions）}"

# **中身は隣の [`ccr-meta.mjs`](./ccr-meta.mjs)。ここは入口だけ。** トークンの読み出し・JSONの
# 組み立て・通信・応答の取り出しは、**プロセスを跨がずに1つの node の中で済ませる**——Windowsでは
# `node` の起動だけで1回44.5msかかり（2026-09-05 の実測）、デーモンはここを繰り返し叩くので、
# 境界の数がそのまま常時の固定費になる。node には `fetch` が入っているので、通信のためにもう1つ
# 起こす必要は無い。
#
# **標準入力はシェルを通さずそのまま渡す。** 変数へ受けると、そこで展開・空白の畳み込みが掛かる。

# `%/*` は区切りが無いと文字列をそのまま返す。**この入口は手で打たれる**ので、`.claude/` の中から
# `bash ccr-meta.sh …` と呼ばれる形も通す。
HERE="${BASH_SOURCE[0]%/*}"
if [[ "$HERE" == "${BASH_SOURCE[0]}" ]]; then HERE='.'; fi

exec node "$HERE/ccr-meta.mjs" "$TOOL"
