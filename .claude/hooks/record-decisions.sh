#!/bin/bash
# UserPromptSubmit hook: 発言に含まれる判断を、作業へ着手する前に履歴へ残させる。
#
# 記録が漏れるのは意志ではなく契機の問題なので、機械で毎回促す。着手後や応答の最後では、
# コンパクションで判断の文脈が失われた後になる。
#
# **ここで促すのは記録だけで、一般則への抽出は促さない。** 1件だけを見て「これは一般則か」は
# 判断できないので、その判定は棚卸し（.claude/skills/policy-review/）へ遅らせてある。
#
# 「判断を含む発言か」の判定は機械では当たらない（キーワード照合は取りこぼしと誤検知が同時に出て、
# どちらも見えない）。機械は促すことだけを担い、判定と記録はモデルが行う。
set -euo pipefail

cat <<'JSON'
{
  "hookSpecificOutput": {
    "hookEventName": "UserPromptSubmit",
    "additionalContext": "記録の確認: 直前の発言が (1) ユーザー本人のものであり（`[デーモン]` で始まる発言はエージェント由来なので対象外）、(2) 判断・好み・方針の選択を含むなら、作業へ着手する前に `.claude/decisions/` へ1件1ファイルで記録する（書式は `.claude/skills/policy-review/SKILL.md`「履歴の書式」）。**発言は原文のまま引き、ここでは一般化しない**——一般則へ畳むのは棚卸しの仕事なので、`.claude/policies.md` と `docs/concept/DesignPrinciples.md` へは書かない。迷ったら書く（履歴は注入されないので、溜めてもコストにならない）。判断を含まない作業依頼・事実の誤りの訂正だけなら何もしない。"
  }
}
JSON
