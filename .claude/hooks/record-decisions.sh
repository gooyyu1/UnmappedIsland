#!/bin/bash
# UserPromptSubmit hook: 発言に含まれる価値観を、作業へ着手する前に記録させる。
#
# 記録が漏れるのは意志ではなく契機の問題なので、機械で毎回促す。着手後や応答の最後では、
# コンパクションで判断の文脈が失われた後になる。
#
# 「価値観を含む発言か」の判定は機械では当たらない（キーワード照合は取りこぼしと誤検知が同時に出て、
# どちらも見えない）。機械は促すことだけを担い、判定と記録はモデルが行う。
set -euo pipefail

cat <<'JSON'
{
  "hookSpecificOutput": {
    "hookEventName": "UserPromptSubmit",
    "additionalContext": "記録の確認: 直前の発言が (1) ユーザー本人のものであり（`[デーモン]` で始まる発言はエージェント由来なので対象外）、(2) A・Bどちらもあり得る場面での選択を含み、(3) 一般論からは再現できない（このリポジトリ特有・ユーザー特有・甲乙つけがたい）なら、作業へ着手する前に、場面・選ぶ方・重視していることを記録する（進め方・設計・レビュー・コードの書き方は .claude/policies.md、ゲーム内容は docs/concept/DesignPrinciples.md、確定した個別の仕様は該当する仕様書）。既存の記録と矛盾するなら追記せず書き換える（最新が正）。3つのどれかを満たさないなら何もしない——一般論に照らして当然の判断・コードや仕様書から一意に導けること・事実の誤りの訂正・選択の余地の無い作業依頼は、記録しない。"
  }
}
JSON
