#!/usr/bin/env bash
# 確定待ちの盤（`meta` の issue）の本文で、チェックの付いている項目を `<番号> <項目>` の行にする。
# 標準入力は `gh issue list --json number,labels,body ...` が返す配列。
#
#   gh issue list --state open --limit 100 --json number,labels,body |
#     bash scripts/agent/checked-items.sh
#
# ## 見張りと盤面で、判定を1つにする
#
# ユーザーの答えは本文のチェックとして付き、**拾われるまでそこに残る**。これを見る場所は2つ
# ある——[`watch-prs.sh`](watch-prs.sh) の `CHECKED`（付いた瞬間に司令塔を起こす）と、
# [`board.sh`](board.sh) の `## 確定待ち`（引き継いだ司令塔が現在地として読む）。**どちらも
# 答えるのは「いま答えが待たれている項目はどれか」という同じ問い**なので、判定はここ1箇所に置く。
# 2箇所に同じ jq を書くと、片方だけが直って**盤面には出るが誰も起こされない**（またはその逆）に
# なる。実際に、`CHECKED` が増分の窓だった間は13件が起こす側に一度も乗らなかった。
#
# ## 見るのは `meta` の issue だけ
#
# **チェックが答えになるのは確定待ちの盤の上だけ**で、`task` issue が本文に持つ手順の一覧は
# ただの覚え書き。区別せずに拾うと、司令塔には下ろす手立てが無いまま毎周それで起こされる。
#
# ## 黙るのは、項目が一覧から下りたとき
#
# 出続けるのが正しい——チェックは出来事ではなく状態で、**拾われるまで残る**。拾った司令塔は答えの
# 行き先を書いてから項目を一覧から消す（CLAUDE.md）ので、そこで `[x]` の箇条書きでなくなる。
# **消したことがそのまま黙る条件になる**ので、判定の側に「処理中」の置き場は要らない。
# **`【確定】` の印は待たない。** 印を付けるのは答えを受けた issue の担当者なので、待つと司令塔の
# 手番が終わったのに一覧が残り、見張りが毎周それで起きて他の待ちに使えなくなる。

set -euo pipefail

# jq は Windows では改行を CRLF で書く（msys の text mode）。番号の突き合わせに使う側があるので、
# ここで `\r` を落としておく。
jq -r '.[]
       | select([.labels[].name] | index("meta"))
       | .number as $number
       | (.body // "")
       | split("\n")[]
       | select(test("^[[:space:]]*[-*][[:space:]]+\\[[xX]\\][[:space:]]"))
       | sub("^[[:space:]]*[-*][[:space:]]+\\[[xX]\\][[:space:]]+"; "")
       | "\($number) \(.)"' | tr -d '\r'
