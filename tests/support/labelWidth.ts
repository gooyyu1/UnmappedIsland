/**
 * 画面に出る文言が枠に収まるかを、フォントを使わずに測るための近似。
 *
 * **Nodeには文字の描画幅を測る手段が無く**、そのためにフォントを依存へ加えたくない。全角1.0・
 * 半角0.5で数えると実測（Noto Sans JP）に対して常に大きめに出る——16uでの英字の平均は0.50字ぶんで、
 * 最も細い並び（illi…）は0.19字ぶん。つまり**この近似で収まれば実物は必ず収まる**。
 */

/** 文言の幅を全角の文字数として近似する（半角は0.5、それ以外は1.0）。 */
export function nameWidth(label: string): number {
  return [...label].reduce((total, char) => total + (/[ -~｡-ﾟ]/.test(char) ? 0.5 : 1), 0);
}
